using System;
using System.Collections.Generic;
using System.Linq;
using RimWorld;
using UnityEngine;
using Verse;

namespace CoolerPsycastsTweaks
{
    /// <summary>
    /// Seven-day cooldown is defined on AbilityDef. Crafted targets yield
    /// their recipe's *nominal* input amounts (100%, no smelting/deconstruct loss).
    /// Ingredient selections are not stored in the resulting Thing by RimWorld:
    /// for alternative ingredients we prefer its Stuff, else a deterministic choice.
    /// </summary>
    public sealed class CompAbilityEffect_RecipeUnmake : CompAbilityEffect
    {
        public override bool CanApplyOn(LocalTargetInfo target, LocalTargetInfo dest)
        {
            Thing thing = target.Thing;
            if (thing == null) return false;
            if (thing is Mineable) return true;
            if (thing is Building b && b.def.building != null && b.def.building.IsDeconstructible) return true;
            if (thing is Pawn p) return p.RaceProps.IsMechanoid && p.kindDef.defName != "CoolPsycasts_ArchotechSplinter";
            return GetRecipe(thing.def) != null || HasBaseCosts(thing.def);
        }

        public override void Apply(LocalTargetInfo target, LocalTargetInfo dest)
        {
            base.Apply(target, dest);
            Thing thing = target.Thing;
            if (thing == null || !thing.Spawned) return;

            if (thing is Mineable mineable)
            {
                // Ore is generated by mining, not crafting; preserve the original behavior.
                mineable.Notify_TookMiningDamage(mineable.MaxHitPoints, parent.pawn);
                mineable.DestroyMined(parent.pawn);
                return;
            }

            if (thing is Pawn pawn)
            {
                // Mechanoid drops are not necessarily a unique original recipe.
                if (!pawn.RaceProps.IsMechanoid || pawn.kindDef.defName == "CoolPsycasts_ArchotechSplinter") return;
                var drops = (pawn.def.butcherProducts ?? new List<ThingDefCountClass>())
                    .Union(pawn.def.killedLeavingsPlayerHostile ?? new List<ThingDefCountClass>()).ToList();
                Map pawnMap = pawn.Map;
                IntVec3 pawnPos = pawn.Position;
                foreach (ThingDefCountClass drop in drops)
                    if (Rand.Chance(drop.DropChance)) SpawnMaterial(drop.thingDef, drop.stuff, drop.count, pawnPos, pawnMap);
                pawn.Destroy(DestroyMode.Vanish);
                return;
            }

            Map map = thing.Map;
            IntVec3 pos = thing.Position;
            int count = Math.Max(1, thing.stackCount);
            List<IngredientOutput> outputs = thing is Building
                ? GetNominalCosts(thing.def, thing.Stuff, 1)
                : GetRecipeOutputs(thing, count);
            if (outputs.Count == 0) return;

            // Vanish: Deconstruct/Smelt would generate additional material (duplication).
            thing.Destroy(DestroyMode.Vanish);
            foreach (IngredientOutput output in outputs)
                SpawnMaterial(output.def, null, output.count, pos, map);
        }

        public override float PsyfocusCostForTarget(LocalTargetInfo target)
        {
            Thing thing = target.Thing;
            if (thing is Mineable m) return Mathf.Clamp(m.HitPoints / 50000f, 0.01f, 0.05f);
            if (thing is Building) return 0.02f;
            if (thing is Pawn p) return Mathf.Clamp(p.RaceProps.baseBodySize * 0.025f, 0.01f, 0.1f);
            return 0.01f;
        }

        public override string ExtraLabelMouseAttachment(LocalTargetInfo target)
        {
            return target.Thing != null && CanApplyOn(target, target)
                ? "AbilityPsyfocusCost".Translate() + ": " + PsyfocusCostForTarget(target).ToStringPercent("0.#")
                : null;
        }

        private static RecipeDef GetRecipe(ThingDef produced)
        {
            return DefDatabase<RecipeDef>.AllDefsListForReading
                .FirstOrDefault(r => r.ProducedThingDef == produced && r.ingredients != null && r.ingredients.Count > 0);
        }

        private static bool HasBaseCosts(ThingDef def)
        {
            return (def.CostList != null && def.CostList.Count > 0) || def.costStuffCount > 0;
        }

        private static List<IngredientOutput> GetRecipeOutputs(Thing thing, int count)
        {
            RecipeDef recipe = GetRecipe(thing.def);
            if (recipe == null) return GetNominalCosts(thing.def, thing.Stuff, count);
            var result = new List<IngredientOutput>();
            // A single recipe can create >1 product; refund per item, rounded down
            // for each stack to avoid artificially generating additional resources.
            int outputCount = 1;
            if (recipe.products != null)
            {
                ThingDefCountClass product = recipe.products.FirstOrDefault(p => p.thingDef == thing.def);
                if (product != null) outputCount = Math.Max(1, product.count);
            }
            foreach (IngredientCount ingredient in recipe.ingredients)
            {
                if (ingredient.filter == null) continue;
                ThingDef chosen = null;
                if (thing.Stuff != null && ingredient.filter.Allows(thing.Stuff))
                    chosen = thing.Stuff;
                if (chosen == null)
                    chosen = ingredient.filter.AllowedThingDefs
                        .Where(d => recipe.fixedIngredientFilter == null || recipe.fixedIngredientFilter.Allows(d))
                        .OrderBy(d => d.defName).FirstOrDefault();
                if (chosen == null) continue;
                int amount = Mathf.FloorToInt(ingredient.GetBaseCount() * count / outputCount);
                AddOrCombine(result, chosen, amount);
            }
            // Recipes with no resolvable ingredients fall back to ThingDef nominal costs.
            return result.Count > 0 ? result : GetNominalCosts(thing.def, thing.Stuff, count);
        }

        private static List<IngredientOutput> GetNominalCosts(ThingDef def, ThingDef stuff, int count)
        {
            var result = new List<IngredientOutput>();
            if (def.CostList != null)
                foreach (ThingDefCountClass ingredient in def.CostList)
                    AddOrCombine(result, ingredient.thingDef, ingredient.count * count);
            if (stuff != null && def.costStuffCount > 0)
                AddOrCombine(result, stuff, def.costStuffCount * count);
            return result;
        }

        private static void AddOrCombine(List<IngredientOutput> result, ThingDef def, int amount)
        {
            if (def == null || amount <= 0) return;
            IngredientOutput existing = result.FirstOrDefault(i => i.def == def);
            if (existing == null) result.Add(new IngredientOutput(def, amount));
            else existing.count += amount;
        }

        private static void SpawnMaterial(ThingDef def, ThingDef stuff, int amount, IntVec3 pos, Map map)
        {
            if (def == null || map == null) return;
            while (amount > 0)
            {
                int n = Math.Min(amount, Math.Max(1, def.stackLimit));
                Thing material = ThingMaker.MakeThing(def, stuff);
                material.stackCount = n;
                GenPlace.TryPlaceThing(material, pos, map, ThingPlaceMode.Near);
                amount -= n;
            }
        }

        private sealed class IngredientOutput
        {
            public readonly ThingDef def;
            public int count;
            public IngredientOutput(ThingDef def, int count) { this.def = def; this.count = count; }
        }
    }

    public sealed class CompProperties_RecipeUnmake : CompProperties_AbilityEffect
    {
        public CompProperties_RecipeUnmake()
        {
            compClass = typeof(CompAbilityEffect_RecipeUnmake);
        }
    }
}
